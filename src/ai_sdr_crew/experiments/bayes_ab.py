"""Bayesian A/B testing for reply rates (Beta-Binomial).

- Posterior of each arm: Beta(prior_a + replies, prior_b + sends - replies).
- P(variant beats control) is computed EXACTLY with the closed form for Beta variables (requires
  an integer alpha on the variant side, which holds for integer priors), evaluated in log space.
- Expected loss of choosing an arm, E[max(p_other - p_arm, 0)], also in closed form.
- Stopping rule: stop when both arms have >= min_sends and the smaller expected loss is below a
  'threshold of caring' epsilon (absolute reply-rate points). Pick the arm with lower loss.
"""

from __future__ import annotations

import math
from dataclasses import dataclass

import numpy as np


def _lbeta(a: float, b: float) -> float:
    return math.lgamma(a) + math.lgamma(b) - math.lgamma(a + b)


def prob_greater(a1: float, b1: float, a2: float, b2: float) -> float:
    """P(X2 > X1) for X1 ~ Beta(a1, b1), X2 ~ Beta(a2, b2). Exact; needs integer a2 >= 1.

    Uses P = sum_{i=0}^{a2-1} B(a1+i, b1+b2) / ((b2+i) B(1+i, b2) B(a1, b1)), with the terms
    generated by their ratio recurrence and summed with log-sum-exp for stability.
    """
    if a2 < 1 or abs(a2 - round(a2)) > 1e-9:
        raise ValueError("a2 must be a positive integer (use integer priors)")
    n = round(a2)
    log_t0 = _lbeta(a1, b1 + b2) - _lbeta(a1, b1)
    if n == 1:
        return float(min(1.0, max(0.0, math.exp(log_t0))))
    i = np.arange(1, n, dtype=float)
    log_ratio = np.log(a1 + i - 1) - np.log(a1 + b1 + b2 + i - 1) + np.log(b2 + i - 1) - np.log(i)
    logs = np.concatenate(([log_t0], log_t0 + np.cumsum(log_ratio)))
    m = float(logs.max())
    total = math.exp(m) * float(np.exp(logs - m).sum())
    return float(min(1.0, max(0.0, total)))


@dataclass(frozen=True)
class Arm:
    name: str
    sends: int
    replies: int

    def __post_init__(self) -> None:
        if self.sends < 0 or not 0 <= self.replies <= self.sends:
            raise ValueError("need 0 <= replies <= sends")

    def posterior(self, prior: tuple[int, int] = (1, 1)) -> tuple[int, int]:
        return prior[0] + self.replies, prior[1] + self.sends - self.replies

    def rate(self) -> float:
        return self.replies / self.sends if self.sends else 0.0


def expected_loss(a_ab: tuple[float, float], b_ab: tuple[float, float]) -> float:
    """E[max(pA - pB, 0)]: expected reply-rate points lost by shipping B when A might be better."""
    (aa, ba), (ab, bb) = a_ab, b_ab
    mean_a = aa / (aa + ba)
    mean_b = ab / (ab + bb)
    # E[pA 1(pA>pB)] = mean_a * P(A+ > B), A+ ~ Beta(aa+1, ba)
    # E[pB 1(pA>pB)] = mean_b * P(A > B+), B+ ~ Beta(ab+1, bb)
    term_a = mean_a * prob_greater(ab, bb, aa + 1, ba)
    term_b = mean_b * prob_greater(ab + 1, bb, aa, ba)
    return max(0.0, term_a - term_b)


@dataclass(frozen=True)
class Decision:
    prob_variant_better: float
    loss_ship_variant: float
    loss_ship_control: float
    stop: bool
    winner: str | None
    reason: str


def decide(
    control: Arm,
    variant: Arm,
    prior: tuple[int, int] = (1, 1),
    epsilon: float = 0.001,
    min_sends: int = 300,
) -> Decision:
    pc = control.posterior(prior)
    pv = variant.posterior(prior)
    p_better = prob_greater(pc[0], pc[1], pv[0], pv[1])
    loss_v = expected_loss(pc, pv)
    loss_c = expected_loss(pv, pc)
    if min(control.sends, variant.sends) < min_sends:
        return Decision(p_better, loss_v, loss_c, False, None, f"fewer than {min_sends} sends/arm")
    best_loss, best = min((loss_v, variant.name), (loss_c, control.name))
    if best_loss < epsilon:
        return Decision(
            p_better, loss_v, loss_c, True, best, f"expected loss {best_loss:.5f} < {epsilon}"
        )
    return Decision(
        p_better, loss_v, loss_c, False, None, f"expected loss {best_loss:.5f} >= {epsilon}"
    )


def monte_carlo_prob_greater(
    a1: float, b1: float, a2: float, b2: float, n: int = 200_000, seed: int = 0
) -> float:
    rng = np.random.default_rng(seed)
    return float((rng.beta(a2, b2, n) > rng.beta(a1, b1, n)).mean())
